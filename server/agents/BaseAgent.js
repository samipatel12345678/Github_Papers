/**
 * BaseAgent class for multi-coding agents bound to a single shared history.
 */

const DBService = require('../services/dbService');
const LLMService = require('../services/llmService');

class BaseAgent {
  constructor({ name, role, systemInstructions, sharedHistory, sessionId }) {
    this.name = name;
    this.role = role;
    this.systemInstructions = systemInstructions;
    this.sharedHistory = sharedHistory;
    this.sessionId = sessionId;
  }

  async executeTurn(taskDescription, provider = 'mock') {
    // 1. Format the single shared history from this agent's perspective
    const messages = await this.sharedHistory.formatForAgent(
      this.name,
      this.role,
      this.systemInstructions
    );

    // 2. Invoke LLM
    const turnResult = await LLMService.generateTurn(
      this.role,
      this.name,
      messages,
      taskDescription,
      provider
    );

    const { thought, content, toolCalls = [] } = turnResult;
    const toolResults = [];

    // 3. Execute any tool calls generated by the agent and save workspace files to MongoDB
    for (const tc of toolCalls) {
      const res = await this._handleToolCall(tc);
      toolResults.push(res);
    }

    // 4. Commit this agent's action and tool results into the Single Shared History
    const entry = await this.sharedHistory.appendEntry({
      senderName: this.name,
      senderRole: this.role,
      messageRole: 'assistant',
      thought,
      content,
      toolCalls,
      toolResults,
      metadata: {
        agentRole: this.role,
        executedToolsCount: toolResults.length
      }
    });

    return entry;
  }

  async _handleToolCall(toolCall) {
    const { id, name, arguments: args } = toolCall;

    try {
      if (name === 'write_file') {
        const { filename, content } = args;
        await DBService.saveWorkspaceFile(this.sessionId, filename, content, this.name);
        return {
          toolCallId: id,
          name,
          output: `Successfully wrote ${content.length} bytes to ${filename} in session workspace.`,
          success: true
        };
      } else if (name === 'read_file') {
        const file = await DBService.getWorkspaceFile(this.sessionId, args.filename);
        if (!file) {
          return {
            toolCallId: id,
            name,
            output: `File '${args.filename}' does not exist in this workspace.`,
            success: false
          };
        }
        return {
          toolCallId: id,
          name,
          output: file.content,
          success: true
        };
      } else if (name === 'execute_test') {
        // Simulated test execution with verified outputs
        return {
          toolCallId: id,
          name,
          output: `[QA Runner Output]:\nRunning testSuite.js...\n✔ Test 1: Capacity & rejection verified\n✔ Test 2: Defensive input validation verified\n✔ Test 3: Cache reset verified\n\nALL 3 TESTS PASSED (0 failures, 12ms)`,
          success: true
        };
      } else {
        return {
          toolCallId: id,
          name,
          output: `Unknown tool '${name}'`,
          success: false
        };
      }
    } catch (err) {
      return {
        toolCallId: id,
        name,
        output: `Tool execution error: ${err.message}`,
        success: false
      };
    }
  }
}

module.exports = BaseAgent;
